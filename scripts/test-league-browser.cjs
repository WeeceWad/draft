const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const auction = require('../src/auction-core.js');
const leagueCore = require('../src/league-core.js');
const packages = process.env.DRAFT_BROWSER_PACKAGES || 'C:/Users/chocc/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules';
const { chromium } = require(require.resolve('playwright', { paths: [packages] }));
const players = JSON.parse(fs.readFileSync(path.resolve(__dirname, '../data/38-0/players.json'), 'utf8'));
const config = { managerCount: 3, names: ['Alex’s All-Time Eleven', 'Sam’s Expensive Signings', 'Charlie’s Bargain Team'], formation: '4-1-2-1-2 (diamond)', mode: 'season', seasonFrom: '1992/93', seasonTo: '2026/27', ratingMin: 40, ratingMax: 95 };
let game = auction.createGame(config, auction.makePool(players, config, leagueCore.seeded(93)).pool);
for (let index = 0; index < game.pool.length; index++) game = auction.buy({ ...game, phase: 'revealed', currentId: game.pool[index].id }, `manager-${index % 3 + 1}`, index === 0 ? 300 : 20).game;
(async () => {
  const browser = await chromium.launch({ headless: true, channel: 'msedge' });
  try {
    const page = await browser.newPage({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(pathToFileURL(path.resolve(__dirname, '../index.html')).href);
    const envelope = { game: auction.serialise(game), showRatings: true, selectedManager: 'manager-1', view: 'league' };
    await page.evaluate(saved => localStorage.setItem('touchline-auction-v1', JSON.stringify(saved)), envelope);
    await page.reload(); await page.locator('#resume').click();
    const saved = () => page.evaluate(() => JSON.parse(localStorage.getItem('touchline-auction-v1')));
    const noOverflow = async () => assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'No horizontal document overflow');
    assert.equal(await page.locator('.award-card').count(), 3);
    assert.equal(await page.locator('.comparison-card').count(), 3);
    assert.match(await page.locator('.award-card').first().innerText(), /£30m/);
    assert(await page.locator('#start-league').isDisabled());
    assert.match(await page.locator('#league-readiness').innerText(), /Place all 11/);
    await page.locator('#finish-teams').click();
    for (let manager = 1; manager <= 3; manager++) {
      await page.locator(`[data-team="manager-${manager}"]`).click();
      await page.locator('#auto-place').click();
      assert.equal((await saved()).game.managers[manager - 1].board.filter(Boolean).length, 11);
    }
    await page.locator('#open-league').click();
    assert(await page.locator('#start-league').isEnabled());
    await page.locator('.comparison-roster').first().locator('summary').click();
    assert.equal(await page.locator('.comparison-player').count(), 33);
    await noOverflow();
    await page.screenshot({ path: path.resolve(__dirname, '../preview-awards-mobile.png'), fullPage: true });
    await page.locator('#ratings-toggle').uncheck();
    assert((await page.locator('.unit-scores strong').allTextContents()).every(value => value === '?'));
    assert((await page.locator('.team-strength').allTextContents()).every(value => value.startsWith('?')));
    assert.equal(await page.locator('.xi-name small').count(), 0);
    assert(!(await page.locator('#award-grid').innerText()).includes('OVR'));
    await page.locator('#start-league').click();
    let current = await saved();
    assert.equal(current.league.round, 0);
    assert.equal(await page.locator('[data-standing]').count(), 3);
    assert.match(await page.locator('#league-progress').innerText(), /0 \/ 6/);
    await page.locator('button[data-view="teams"]').click();
    assert.equal(await page.locator('.slot-button:disabled').count(), 11);
    assert.equal(await page.locator('[data-unplace]').count(), 0);
    assert(await page.locator('#auto-place').isDisabled());
    await page.locator('button[data-view="auction"]').click();
    assert(await page.locator('#undo-final').isDisabled());
    await page.locator('button[data-view="league"]').click();
    await page.locator('#play-round').click();
    const firstRound = await saved();
    assert.equal(firstRound.league.round, 1);
    assert.equal(await page.locator('#latest-matchday details.fixture-card').count(), 1);
    const restoredGame = auction.restore(firstRound.game, players);
    const league = leagueCore.restore(firstRound.league, restoredGame);
    const firstResult = league.fixtures.find(fixture => fixture.result).result;
    assert.equal(await page.locator('#latest-matchday .fixture-score').innerText(), `${firstResult.homeGoals} – ${firstResult.awayGoals}`);
    await page.reload(); await page.locator('#resume').click();
    assert.deepEqual(await saved(), firstRound, 'Reload must preserve the league seed, matchday, XIs and rating preference');
    assert.equal(await page.locator('#latest-matchday .fixture-score').innerText(), `${firstResult.homeGoals} – ${firstResult.awayGoals}`);
    await page.locator('#ratings-toggle').check();
    assert((await page.locator('.unit-scores strong').allTextContents()).every(value => /^\d+$/.test(value)));
    await page.locator('#finish-league').click();
    current = await saved();
    assert.equal(current.league.round, 6);
    assert(await page.locator('#champion').isVisible());
    assert(await page.locator('#league-controls').isHidden());
    const finalLeague = leagueCore.restore(current.league, auction.restore(current.game, players));
    assert(finalLeague.fixtures.every(fixture => fixture.result));
    assert(leagueCore.table(finalLeague).every(row => row.played === 4));
    await page.locator('.fixture-history>summary').click();
    assert.equal(await page.locator('#fixture-list details.fixture-card').count(), 6);
    for (const width of [320, 390, 430, 1440]) {
      await page.setViewportSize({ width, height: 900 }); await noOverflow();
      assert(await page.evaluate(() => document.querySelector('.standing-points').getBoundingClientRect().right <= document.getElementById('league-table').getBoundingClientRect().right + 1), 'Points stay visible in the mobile table');
    }
    await page.setViewportSize({ width: 390, height: 844 });
    await page.locator('#full-table').check();
    assert(await page.locator('thead .stat-extra').first().isVisible());
    await noOverflow(); await page.locator('#full-table').uncheck();
    await page.screenshot({ path: path.resolve(__dirname, '../preview-league-mobile.png'), fullPage: true });
    await page.setViewportSize({ width: 1440, height: 1100 });
    await page.screenshot({ path: path.resolve(__dirname, '../preview-league-desktop.png'), fullPage: true });
    await page.reload(); await page.locator('#resume').click();
    assert.equal((await saved()).league.round, 6);
    assert(await page.locator('#champion').isVisible());
    await page.locator('#open-settings').click(); await page.locator('#start').click();
    assert.equal((await saved()).league, null, 'New game clears the old league');
    await page.locator('button[data-view="league"]').click();
    assert(await page.locator('#league-waiting').isVisible());
    assert(await page.locator('#post-auction').isHidden());
    assert.deepEqual(errors, []);
    console.log('League browser checks passed: awards, XIs, auto-placement, readiness, hidden ratings, lineup locks, matchdays, scores/scorers, final table, save/resume and new-game reset at 320/390/430/1440px.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
